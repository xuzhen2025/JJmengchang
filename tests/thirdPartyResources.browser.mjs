  await page.screenshot({ path: "tmp/third-party-detail.png" });
  await button("返回第三方列表").click();
  await page.getByTestId("thirdParty-primary-filter").getByRole("button", { name: "美妆", exact: true }).click();
  await expect(cards()).toHaveCount(2);
  await page.getByTestId("thirdParty-secondary-filter").getByRole("button", { name: "特写质感镜头", exact: true }).click();
  await expect(cards()).toHaveCount(1);
  await button("重置").click();
  await expect(cards()).toHaveCount(6);
  await button("选择").click();
  await cards().first().getByTitle("选择此项", { exact: true }).click();
  await button("修改").click();
  await page.getByRole("menuitem", { name: "修改状态", exact: true }).click();
  const statusDialog = page.getByRole("dialog", { name: "修改状态", exact: true });
  await statusDialog.getByRole("combobox").selectOption("画面利用");
  await statusDialog.getByRole("button", { name: "确定", exact: true }).click();
  await expect(cards().first()).toContainText("画面利用");
  await button("素材管理").click();
  await expect(page.getByTestId("material-resource-view")).toHaveAttribute("data-resource-scope", "materials");
  await expect(page.getByText("0920-精华液质地展示-品牌供片.mp4", { exact: true })).toHaveCount(0);
  await button("第三方管理").click();
  await expect(cards().first()).toContainText("画面利用");
  await switchMode("管理端");
  await button("分类管理").click();
  const root = page.getByTestId("category-management");
  await root.getByRole("button", { name: "第三方", exact: true }).click();
  const parent = root.locator('[data-category-id="third-mat-c1"]');
  await parent.click();
  await parent.getByTitle("删除分类").click();
  await expect(page.getByRole("status")).toContainText("存在资源");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const child = root.locator('[data-category-id="third-mat-c1-3"]');
  await child.getByTitle("删除分类").click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await child.getByTitle("编辑名称").click();
  const edit = page.getByRole("dialog").last();
  await edit.getByRole("textbox").fill("品牌质地特写");
  await edit.getByRole("button", { name: "确定", exact: true }).click();
