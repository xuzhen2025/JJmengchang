  await page.locator("#sidebar-item-resources").click();
  await button("素材管理").click();
  const materialLayout = await page.getByTestId("material-resource-view").getAttribute("class");
  await page.screenshot({ path: "tmp/materials-reference.png" });
  await button("第三方管理").click();
  await expect(cards()).toHaveCount(6);
  assert.equal(await page.getByTestId("material-resource-view").getAttribute("class"), materialLayout);
  await expect(page.getByTestId("material-resource-view")).toHaveAttribute("data-resource-scope", "thirdParty");
  await expect.poll(() => cards().locator("img").evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0))).toBe(true);
  await page.screenshot({ path: "tmp/third-party-desktop.png" });
  await cards().first().hover();
  await expect.poll(() => cards().first().locator("video").evaluate(v => v.readyState >= 2)).toBe(true);
  await cards().first().click();
  await expect(button("返回第三方列表")).toBeVisible();
  await expect(page.getByText("第三方区", { exact: true })).toBeVisible();
